# -*- coding: utf-8 -*-
"""Проход «ё»: только однозначные случаи.

Безопасные правила:
  * «еще» → «ещё», «ее» → «её» (отдельное слово; «нее» не затрагивается);
  * глаголы с фиксированным корнем и окончаниями -ет/-ешь/-ем/-ете → -ёт/-ёшь/-ём/-ёте
    (в русском ударение на «ё» не падает больше никуда, поэтому в этих
    окончаниях «е» — всегда ошибка);
  * закрытый список существительных и прилагательных (чёрный, счёт, приём,
    подъём, мёртвый, сёстры, звёзды, тётя, жёсткий, лёгкий).

Чего проход НЕ делает: «все»/«всё», «все-таки», «меры», «небо», «дядя» —
там «е» или нормально, или решение неоднозначно.

Запуск: python3 tools/apply_yo.py [--apply]
"""
import csv
import glob
import re
import sys
from collections import Counter

APPLY = "--apply" in sys.argv

VERB_STEMS = [
    "бер", "вед", "ид", "найд", "прид", "уйд", "пойд", "пройд", "перейд", "войд",
    "возьм", "начн", "жд", "дожд", "соль", "ль", "пь", "бь", "шл", "кр", "уч",
    "умр", "рем", "плод", "чм", "пря", "сек", "теч", "влеч", "влечё",
]
ENDINGS = {"ет": "ёт", "ешь": "ёшь", "ем": "ём", "ете": "ёте"}

PAIRS = [("еще", "ещё"), ("ее", "её"), ("Еще", "Ещё"), ("Ее", "Её")]
for stem in VERB_STEMS:
    for wrong_end, right_end in ENDINGS.items():
        PAIRS.append((stem + wrong_end, stem + right_end))
PAIRS += [
    ("черный", "чёрный"), ("черная", "чёрная"), ("черное", "чёрное"),
    ("черные", "чёрные"), ("черных", "чёрных"), ("черным", "чёрным"),
    ("черного", "чёрного"), ("черной", "чёрной"), ("черному", "чёрному"),
    ("черную", "чёрную"), ("чёрт", "чёрт"),
    ("счет", "счёт"), ("счета", "счёта"), ("счету", "счёту"), ("счетом", "счётом"),
    ("счете", "счёте"), ("счетов", "счётов"),
    ("прием", "приём"), ("приема", "приёма"), ("приеме", "приёме"), ("приемом", "приёмом"),
    ("подъем", "подъём"), ("подъема", "подъёма"), ("подъеме", "подъёме"),
    ("мертвый", "мёртвый"), ("мертвая", "мёртвая"), ("мертвое", "мёртвое"),
    ("мертвые", "мёртвые"), ("мертвых", "мёртвых"), ("мертвым", "мёртвым"),
    ("мертвого", "мёртвого"), ("мертвой", "мёртвой"),
    ("сестра", "сестра"), ("сестры", "сёстры"), ("сестру", "сестру"),
    ("сестры", "сёстры"), ("сестрам", "сёстрам"),
    ("звезда", "звезда"), ("звезды", "звёзды"), ("звезд", "звёзд"), ("звездам", "звёздам"),
    ("тетя", "тётя"), ("тети", "тёти"), ("тетей", "тётей"),
    ("жесткий", "жёсткий"), ("жесткая", "жёсткая"), ("жесткие", "жёсткие"),
    ("жестким", "жёстким"), ("жестко", "жёстко"), ("жесткость", "жёсткость"),
    ("легкий", "лёгкий"), ("легкая", "лёгкая"), ("легкие", "лёгкие"),
    ("легких", "лёгких"), ("легким", "лёгким"), ("легко", "легко"),
]
# пары-дубли убираем, оставляя первую непустую
seen = set()
UNIQUE = []
for w, r in PAIRS:
    if w != r and (w, r) not in seen:
        seen.add((w, r))
        UNIQUE.append((w, r))
PAIRS = sorted(UNIQUE, key=lambda p: -len(p[0]))

stats = Counter()
changed_files = 0
changed_rows = 0

for path in sorted(glob.glob("translation/ru_RU/*/*.csv")):
    with open(path, encoding="utf-8", newline="") as fh:
        raw = fh.read()
    newline = "\r\n" if "\r\n" in raw else "\n"
    rows = list(csv.reader(raw.splitlines(keepends=True)))
    dirty = False

    for row in rows:
        if len(row) < 5:
            continue
        before = row[4]
        cell = before
        for wrong, right in PAIRS:
            for w, r in ((wrong, right), (wrong.capitalize(), right.capitalize())):
                if w in cell:
                    n = cell.count(w)
                    cell = re.sub(
                        r"(?<![А-Яа-яЁё])" + re.escape(w) + r"(?![А-Яа-яЁё])", r, cell
                    )
                    stats[w] += n
        if cell != before:
            assert "ёё" not in cell, cell
            row[4] = cell
            dirty = True
            changed_rows += 1

    if dirty:
        changed_files += 1
        if APPLY:
            with open(path, "w", encoding="utf-8", newline="") as fh:
                csv.writer(fh, lineterminator=newline).writerows(rows)

print("режим:", "ПРИМЕНЕНИЕ" if APPLY else "пробный (--apply не указан)")
print("правил:", len(PAIRS), "| строк изменено:", changed_rows, "| файлов:", changed_files)
RIGHT = dict(PAIRS)
RIGHT.update({w.capitalize(): r.capitalize() for w, r in PAIRS})
for w, n in stats.most_common(25):
    print(f"   {w:12} → {RIGHT.get(w, '?'):12} {n}")
print("всего вхождений:", sum(stats.values()))
